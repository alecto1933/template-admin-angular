const iconsDir = resolve('node_modules/lucide-static/icons');
const target = resolve('src/app/shared/ui/icon/icons.ts');

const entries = ICONS.map((name) => {
  const source = readFileSync(resolve(iconsDir, `${name}.svg`), 'utf8');
  const inner = source
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>[\s\S]*$/, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+/g, ' ')
    .trim();

  if (!inner) {
    throw new Error(`Could not read the body of icon "${name}"`);
  }

  return `  '${name}': ${JSON.stringify(inner)},`;
});

const file = `// Generated by scripts/sync-icons.mjs. Do not edit by hand.
// Source: lucide-static (ISC license) - https://lucide.dev
export const ICONS = {
${entries.join('\n')}
} as const;

export type IconName = keyof typeof ICONS;
`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, file);
console.log(`Wrote ${ICONS.length} icons to ${target}`);
